#!/usr/bin/env python3
"""Inline switch/instructions/*.md into the Switch template.

switch/receipts.template.src.yaml marks where each agent's instructions go
with `instructions: "{{clerk.md}}"`. This writes switch/receipts.template.yaml,
the file you import into Switch Console. Run it after editing the .md files.
"""
import pathlib
import re

root = pathlib.Path(__file__).resolve().parent.parent
src = (root / "switch/receipts.template.src.yaml").read_text()


def inline(m):
    indent, name = m.group(1), m.group(2)
    body = (root / "switch/instructions" / name).read_text().rstrip("\n")
    pad = indent + "  "
    return f"{indent}instructions: |\n" + "\n".join(pad + l if l else "" for l in body.splitlines())


out = re.sub(r'^( *)instructions: "\{\{([\w.-]+\.md)\}\}"$', inline, src, flags=re.M)
out = "# GENERATED by scripts/build-template.py from receipts.template.src.yaml. Edit that, not this.\n" + out
(root / "switch/receipts.template.yaml").write_text(out)
print("wrote switch/receipts.template.yaml")
